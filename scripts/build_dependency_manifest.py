def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    args = parser.parse_args()
    source_root = args.source_root.resolve()
    entries = []
    for relative, purpose, redistribution in DEPENDENCIES:
        source = source_root / relative
        published = ROOT / relative
        if not source.is_file() or not published.is_file():
            raise SystemExit(f"Missing dependency: {relative}")
        source_sha = sha256(source)
        published_sha = sha256(published)
        entries.append(
            {
                "path": relative,
                "source_bytes": source.stat().st_size,
                "source_sha256": source_sha,
                "published_bytes": published.stat().st_size,
                "published_sha256": published_sha,
                "purpose": purpose,
                "redistribution_basis": redistribution,
                "transform": "path-redaction" if source_sha != published_sha else "verbatim",
            }
        )
    result = {
        "status": "complete",
        "source_root": "<SOURCE_ROOT>",
        "external_requirements": {
            "proteinbase": "v2026-11-01, revision 2d2825070da5ba77e0c7e1a0942146e8307e9282",
            "anthropic_release": "v1.0, revision 9e1b81696da46835e9e9cde9a3da976e0abc92ab",
            "ipsae": "DunbrackLab/IPSAE commit 6174cf9e71cb1bd660cc805856a18c4871a6dec3",
            "pinc": "official implementation commit 57afb08e29fe97379db5b155da5fb78c4c8715d1",
        },
        "dependencies": entries,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(entries)} dependencies")


if __name__ == "__main__":
    main()
